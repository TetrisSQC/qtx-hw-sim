"""Generate Pascal data units from the C sources of c64-hw-simulator.
   - board data (c64_board_data.c, zx48_board_data.c) -> hwsim.bd_c64.pas / hwsim.bd_zx48.pas
   - ROMs (c64-roms.h, zx48-rom.h) and cartridges -> hwsim.roms.pas (base64 strings)
Usage: python gen_data.py <c-src-root> <out-dir> [--rom KEY=FILE ...]"""
import re, sys, os, base64

root, out = sys.argv[1], sys.argv[2]
given = dict(a.split("=", 1) for a in sys.argv[4:] if sys.argv[3:4] == ["--rom"]) if len(sys.argv) > 4 else {}

# key -> file under qtx/data (optional, see roms())
EXTRA_ROMS = [("apple2p_main", "apple2roms/apple.rom"), ("apple2p_char", "apple2roms/3410036.bin"),
              # LC-80 (../../lc80): D202/D203 (U505, 1K each) as on the schematic; the 2716 board, the LC-80.2,
              # the LC-80e (chess)
              ("lc80_d202", "../../lc80/bm075.d202"), ("lc80_d203", "../../lc80/bm076.d203"),
              ("lc80a_2716", "../../lc80/lc80a/lc80_2716.bin"), ("lc80_2", "../../lc80/lc80_2/lc80_2.bin"),
              ("lc80e_0000", "../../lc80/lc80e/lc80e-0000-schach.rom"),
              ("lc80e_1000", "../../lc80/lc80e/lc80e-1000-schach.rom"),
              ("lc80e_c000", "../../lc80/lc80e/lc80e-c000-schach.rom")]

def embedded(path):
    """The ROM images already in hwsim.roms.pas: key -> bytes."""
    res = {}
    if not os.path.exists(path):
        return res
    txt = open(path, encoding="utf-8").read()
    for m in re.finditer(r"  B64_(\w+) =\n((?:    '[^']*'(?: \+)?;?\n)+)", txt):
        b64 = "".join(re.findall(r"'([^']*)'", m.group(2)))
        res[m.group(1).lower()] = base64.b64decode(b64)
    return res

def pstr(s):
    return "'" + s.replace("'", "''") + "'"

def board(cfile, unit, var):
    txt = open(os.path.join(root, "src", cfile), encoding="utf-8").read()
    nets = re.search(r"static const char \*const nets\[\] = \{(.*?)\};", txt, re.S).group(1)
    nets = re.findall(r'"([^"]*)"', nets)
    pads = re.findall(r'\{ "([^"]*)", ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f, (-?\d+) \}', txt)
    comps = re.findall(r'\{ "([^"]*)", "([^"]*)", "([^"]*)", (\d+), (\d+) \}', txt)
    m = re.search(r"const board_data_t \w+ = \{\s*\{ ([^}]*) \},\s*nets, (\d+), pads, (\d+), comps, (\d+),", txt)
    outline = [x.strip().rstrip("f") for x in m.group(1).split(",")]
    assert int(m.group(2)) == len(nets) and int(m.group(3)) == len(pads) and int(m.group(4)) == len(comps), cfile
    L = []
    L.append("unit %s;" % unit)
    L.append("")
    L.append("{ GENERATED by tools/gen_data.py from %s - do not edit. }" % cfile)
    L.append("")
    L.append("interface")
    L.append("")
    L.append("uses hwsim.boarddata;")
    L.append("")
    L.append("function %s: TBoardData;" % var)
    L.append("")
    L.append("implementation")
    L.append("")
    L.append("const")
    L.append("  NETS: array[0..%d] of String = [" % (len(nets) - 1))
    L.append(",\n".join("    " + pstr(n) for n in nets))
    L.append("  ];")
    L.append("  PADS: array[0..%d] of TBdPad = [" % (len(pads) - 1))
    L.append(",\n".join("    (name: %s; x: %s; y: %s; w: %s; h: %s; net: %s)" % (pstr(p[0]), *p[1:]) for p in pads))
    L.append("  ];")
    L.append("  COMPS: array[0..%d] of TBdComp = [" % (len(comps) - 1))
    L.append(",\n".join("    (ref: %s; value: %s; footprint: %s; first_pad: %s; npads: %s)" %
                        (pstr(c[0]), pstr(c[1].replace('\\"', '"')), pstr(c[2]), c[3], c[4]) for c in comps))
    L.append("  ];")
    L.append("")
    L.append("var FData: TBoardData;")
    L.append("")
    L.append("function %s: TBoardData;" % var)
    L.append("var i: Integer;")
    L.append("begin")
    L.append("  if FData = nil then begin")
    L.append("    FData := TBoardData.Create;")
    L.append("    FData.outline[0] := %s; FData.outline[1] := %s; FData.outline[2] := %s; FData.outline[3] := %s;" % tuple(outline))
    L.append("    FData.nnets := %d; FData.npads := %d; FData.ncomps := %d;" % (len(nets), len(pads), len(comps)))
    L.append("    FData.nets.SetLength(FData.nnets);")
    L.append("    for i := 0 to FData.nnets - 1 do FData.nets[i] := NETS[i];")
    L.append("    FData.pads.SetLength(FData.npads);")
    L.append("    for i := 0 to FData.npads - 1 do FData.pads[i] := PADS[i];")
    L.append("    FData.comps.SetLength(FData.ncomps);")
    L.append("    for i := 0 to FData.ncomps - 1 do FData.comps[i] := COMPS[i];")
    L.append("  end;")
    L.append("  Result := FData;")
    L.append("end;")
    L.append("")
    L.append("end.")
    open(os.path.join(out, unit + ".pas"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print(unit, len(nets), len(pads), len(comps))

def c_arrays(hfile):
    txt = open(os.path.join(root, "chips", hfile), encoding="utf-8").read()
    res = {}
    for m in re.finditer(r"(?:static )?(?:const )?unsigned char (\w+)\[(\d+)\] = \{(.*?)\};", txt, re.S):
        data = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(3)))
        assert len(data) == int(m.group(2)), m.group(1)
        res[m.group(1)] = data
    return res

def b64_const(name, data):
    s = base64.b64encode(data).decode()
    parts = [s[i:i + 100] for i in range(0, len(s), 100)] or [""]
    return "  %s =\n" % name + " +\n".join("    '%s'" % p for p in parts) + ";\n"

# ROMs that may not be published (Apple's): they go into hwsim.roms_local. src/hwsim.roms_local.pas is an
# empty stub (checked in: the Apple then runs its test ROM); the filled unit is written to src/local/
# (not checked in), which tools/build.py copies over the stub.
PRIVATE_ROMS = {"apple2p_main", "apple2p_char"}


def rom_unit(unit, arrs, carts):
    L = ["unit %s;" % unit, "", "{ GENERATED by tools/gen_data.py - do not edit. ROM images as base64. }", "",
         "interface", "", "uses hwsim.util;", ""]
    for k in arrs:
        L.append("function ROM_%s: TBytes;" % k.upper())
    if carts is not None:
        L += ["", "{ Built-in cartridge/ROM files by file name (empty array if unknown). }",
              "function BuiltinFile(const name: String): TBytes;", "function BuiltinFileNames: array of String;"]
    L += ["", "implementation", "", "const"]
    for k, d in arrs.items():
        L.append(b64_const("B64_" + k.upper(), d))
    for i, (f, d) in enumerate((carts or {}).items()):
        L.append(b64_const("B64_FILE%d" % i, d))
    L.append("var")
    for k in arrs:
        L.append("  F_%s: TBytes;" % k.upper())
    L.append("")
    for k in arrs:
        L += ["function ROM_%s: TBytes;" % k.upper(), "begin",
              "  if F_%s = nil then F_%s := Base64ToBytes(B64_%s);" % (k.upper(), k.upper(), k.upper()),
              "  Result := F_%s;" % k.upper(), "end;", ""]
    if carts is not None:
        L += ["function BuiltinFile(const name: String): TBytes;", "begin", "  Result := nil;"]
        for i, f in enumerate(carts):
            L.append("  if name = %s then Result := Base64ToBytes(B64_FILE%d);" % (pstr(f), i))
        L += ["end;", "", "function BuiltinFileNames: array of String;", "begin"]
        for f in carts:
            L.append("  Result.Add(%s);" % pstr(f))
        L += ["end;", ""]
    L.append("end.")
    return "\n".join(L) + "\n"


def roms():
    arrs = {}
    arrs.update(c_arrays("c64-roms.h"))
    arrs.update(c_arrays("zx48-rom.h"))
    # ROMs that are not part of hw-sim (user-supplied). The ROM units are their home: a file is only read
    # when it is there, otherwise the image already embedded is kept (empty: the machine's test ROM).
    # Embed a new one with:  python tools/gen_data.py <c-src-root> <out-dir> --rom KEY=FILE
    kept = embedded(os.path.join(out, "hwsim.roms.pas"))
    kept.update({k: v for k, v in embedded(os.path.join(out, "local", "hwsim.roms_local.pas")).items() if v})
    data = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
    for key, f in EXTRA_ROMS:
        path = os.path.join(data, f)
        if key in given:
            arrs[key] = open(given[key], "rb").read()
        elif os.path.exists(path):
            arrs[key] = open(path, "rb").read()
        else:
            arrs[key] = kept.get(key, b"")
    carts = {}
    for f in sorted(os.listdir(os.path.join(root, "carts"))):
        if f.endswith((".crt", ".rom")):
            carts[f] = open(os.path.join(root, "carts", f), "rb").read()
    public = {k: v for k, v in arrs.items() if k not in PRIVATE_ROMS}
    private = {k: v for k, v in arrs.items() if k in PRIVATE_ROMS}
    open(os.path.join(out, "hwsim.roms.pas"), "w", encoding="utf-8", newline="\n").write(rom_unit("hwsim.roms", public, carts))
    open(os.path.join(out, "hwsim.roms_local.pas"), "w", encoding="utf-8", newline="\n").write(
        rom_unit("hwsim.roms_local", {k: b"" for k in private}, None))
    if any(private.values()):
        os.makedirs(os.path.join(out, "local"), exist_ok=True)
        open(os.path.join(out, "local", "hwsim.roms_local.pas"), "w", encoding="utf-8", newline="\n").write(
            rom_unit("hwsim.roms_local", private, None))
    print("roms", {k: len(v) for k, v in public.items()}, list(carts))
    print("private roms (src/local)", {k: len(v) for k, v in private.items()})

board("c64_board_data.c", "hwsim.bd_c64", "BoardC64")
board("zx48_board_data.c", "hwsim.bd_zx48", "BoardZX48")
roms()
