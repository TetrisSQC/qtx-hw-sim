"""gen_lc80.py - LC-80 board data from the hand-captured netlist (qtx/data/lc80/lc80.pins.txt).

The schematic is a scan without a PCB, so the geometry is synthesized: the ICs at the X/Y of the
netlist file (horizontal DIPs, pin 1 lower left), passives and transistors in a strip on the right.
The keyboard keys (KEY lines) become a table for the machine: a key joins two nets.

Usage: python gen_lc80.py <pins.txt> <out-dir>"""
import sys, os, collections

src, out = sys.argv[1], sys.argv[2]

PINS = {"UD880D": 40, "U505D": 24, "U214D": 18, "DS8205": 16, "UD855D": 40, "UD857D": 28,
        "DL014": 14, "DL000": 14, "VQE23": 18}
PITCH = 2.54

comps = []     # (ref, type, x, y, {pin: net})
keys = []      # (name, sysb, userb)
for line in open(src, encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    t = line.split()
    if t[0] == "KEY":
        keys.append((t[1], int(t[2]), int(t[3])))
        continue
    ref, typ, x, y = t[0], t[1], t[2], t[3]
    pins = {}
    for kv in t[4:]:
        p, n = kv.split("=", 1)
        assert p not in pins, (ref, p)
        pins[p] = n
    comps.append((ref, typ, None if x == "*" else float(x), None if y == "*" else float(y), pins))

nets = sorted({n for c in comps for n in c[4].values()})
for k in keys:      # the key nets must exist
    for n in ("DIG%d" % (k[1] - 2), "KIN%d" % (k[2] - 4)):
        assert n in nets, n
for n in ("RESKEY", "NMIKEY", "OSC", "GND", "+5V"):
    assert n in nets, n
net_index = {n: i for i, n in enumerate(nets)}

# every net should have at least two pins (else a typo in the capture)
use = collections.Counter(n for c in comps for n in c[4].values())
single = [n for n in nets if use[n] < 2 and not n.startswith(("UPA", "UPB", "UA", "UB", "ZCTO", "TRG", "TAPEOUT"))]
if single:
    print("nets with one pin:", " ".join(single))


def dip_pads(n, cx, cy):
    half = n // 2
    rowsep = 15.24 if n >= 24 else 7.62
    x0 = cx - (half - 1) * PITCH / 2
    pads = []
    for i in range(n):
        if i < half:
            pads.append((str(i + 1), x0 + i * PITCH, cy + rowsep / 2))
        else:
            pads.append((str(i + 1), x0 + (n - 1 - i) * PITCH, cy - rowsep / 2))
    return pads


layout = []
misc_x0, misc_y = 315.0, 25.0
misc_x = misc_x0
for ref, typ, x, y, pins in comps:
    if typ in PINS:
        pads = dip_pads(PINS[typ], x, y)
        w = h = 1.6
        fp = "DIP-%d" % PINS[typ]
    else:
        names = sorted(pins, key=lambda p: (len(p), p))
        width = (len(names) - 1) * PITCH
        if misc_x > misc_x0 and misc_x + width > misc_x0 + 70:
            misc_x, misc_y = misc_x0, misc_y + 6.0
        pads = [(p, misc_x + i * PITCH, misc_y) for i, p in enumerate(names)]
        misc_x += width + 6.0
        w = h = 1.4
        fp = "MISC-%d" % len(pads)
    full = [(name, px, py, w, h, net_index[pins[name]] if name in pins else -1) for name, px, py in pads]
    layout.append((ref, typ, fp, full))

xs = [p[1] for _, _, _, pads in layout for p in pads]
ys = [p[2] for _, _, _, pads in layout for p in pads]
outline = (min(xs) - 8, min(ys) - 8, max(xs) + 8, max(ys) + 8)


def pstr(s):
    return "'" + s.replace("'", "''") + "'"


allpads = [p for _, _, _, pads in layout for p in pads]
L = ["unit hwsim.bd_lc80;", "",
     "{ GENERATED by tools/gen_lc80.py from data/lc80/lc80.pins.txt - do not edit.",
     "  LC-80 (G-5403.500): netlist captured by hand from the schematic scan, geometry synthesized. }", "",
     "interface", "", "uses hwsim.boarddata;", "",
     "type", "  TLc80Key = record name: String; sysb, userb: Integer; end;", "",
     "const", "  LC80_KEYS: array[0..%d] of TLc80Key = [" % (len(keys) - 1)]
L.append(",\n".join("    (name: %s; sysb: %d; userb: %d)" % (pstr(k[0]), k[1], k[2]) for k in keys))
L += ["  ];", "", "function BoardLc80: TBoardData;", "", "implementation", "", "const"]
L.append("  NETS: array[0..%d] of String = [" % (len(nets) - 1))
L.append(",\n".join("    " + pstr(n) for n in nets))
L.append("  ];")
L.append("  PADS: array[0..%d] of TBdPad = [" % (len(allpads) - 1))
L.append(",\n".join("    (name: %s; x: %.3f; y: %.3f; w: %.3f; h: %.3f; net: %d)" % (pstr(p[0]), p[1], p[2], p[3], p[4], p[5])
                    for p in allpads))
L.append("  ];")
L.append("  COMPS: array[0..%d] of TBdComp = [" % (len(layout) - 1))
first = 0
rows = []
for ref, typ, fp, pads in layout:
    rows.append("    (ref: %s; value: %s; footprint: %s; first_pad: %d; npads: %d)" % (pstr(ref), pstr(typ), pstr(fp), first, len(pads)))
    first += len(pads)
L.append(",\n".join(rows))
L.append("  ];")
L += ["", "var FData: TBoardData;", "", "function BoardLc80: TBoardData;", "var i: Integer;", "begin",
      "  if FData = nil then begin", "    FData := TBoardData.Create;",
      "    FData.outline[0] := %.3f; FData.outline[1] := %.3f; FData.outline[2] := %.3f; FData.outline[3] := %.3f;" % outline,
      "    FData.nnets := %d; FData.npads := %d; FData.ncomps := %d;" % (len(nets), len(allpads), len(layout)),
      "    FData.nets.SetLength(FData.nnets);", "    for i := 0 to FData.nnets - 1 do FData.nets[i] := NETS[i];",
      "    FData.pads.SetLength(FData.npads);", "    for i := 0 to FData.npads - 1 do FData.pads[i] := PADS[i];",
      "    FData.comps.SetLength(FData.ncomps);", "    for i := 0 to FData.ncomps - 1 do FData.comps[i] := COMPS[i];",
      "  end;", "  Result := FData;", "end;", "", "end."]
open(os.path.join(out, "hwsim.bd_lc80.pas"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("lc80: %d parts, %d pads, %d nets, %d keys" % (len(layout), len(allpads), len(nets), len(keys)))
